const DICTS: Record<UiLanguage, Dict> = { en, fr, ar, tn };

export function translate(key: StringKey, lang: UiLanguage, vars?: Record<string, string | number>): string {
  let s = DICTS[lang]?.[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = usePrefs((s) => s.uiLanguage);
  return (key: StringKey, vars?: Record<string, string | number>) => translate(key, lang, vars);
}

/** Localised message for an API error code, falling back to the server's own (English) message. */
export function useErrorMessage() {
  const t = useT();
  return (e: unknown): string => {
    const code = (e as { code?: string })?.code;
    const known: Record<string, StringKey> = {
      RATE_LIMITED: "error.RATE_LIMITED",
      PROVIDER_ERROR: "error.PROVIDER_ERROR",
      AI_DISABLED: "error.AI_DISABLED",
      AI_NOT_CONFIGURED: "error.AI_NOT_CONFIGURED",
      NETWORK: "error.NETWORK",
      UNAUTHORIZED: "error.UNAUTHORIZED",
    };
    if (code && known[code]) return t(known[code]);
    return e instanceof Error && e.message ? e.message : t("error.generic");
  };
}

/** Translates `message` when it is a string key (used for errors thrown by stores), else returns it as is. */
export function translateMessage(message: string, lang: UiLanguage): string {
  return message in en ? translate(message as StringKey, lang) : message;
}
